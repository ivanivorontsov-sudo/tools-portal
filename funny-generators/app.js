function generateFive(){
  const generated=[];
  let guard=0;
  while(generated.length<5 && guard<50){
    guard++;
    const phrase=makePhrase();
    if(!generated.includes(phrase)) generated.push(phrase);
  }
  $("options").replaceChildren();
  generated.forEach(phrase=>{
    const li=document.createElement("li");
    const button=document.createElement("button");
    button.type="button";
    button.textContent=phrase;
    button.addEventListener("click",()=>setResult(phrase));
    li.append(button);
    $("options").append(li);
  });
  $("batch").classList.remove("hidden");
  $("toast").textContent="Готово: пять альтернативных версий реальности.";
  if(generated.length) setResult(generated[0]);
  $("batch").classList.remove("hidden");
}
async function copyText(text,source){
  if(!text)return;
  try{
    if(navigator.clipboard && window.isSecureContext){
      await navigator.clipboard.writeText(text);
      $("toast").textContent="Скопировано. Можешь вставлять и делать вид, что так и было задумано.";
    }else{
      const area=document.createElement("textarea");
      area.value=text;
      area.setAttribute("readonly","");
      area.style.position="fixed";
      area.style.opacity="0";
      document.body.append(area);
      area.select();
      const ok=document.execCommand("copy");
      area.remove();
      $("toast").textContent=ok?"Скопировано.":"Браузер не дал скопировать — выдели текст вручную.";
    }
  }catch{
    $("toast").textContent="Не удалось скопировать. Выдели текст вручную.";
  }
}
