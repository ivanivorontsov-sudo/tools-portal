let current="mom";
let lastByMode=Object.create(null);
let currentText="";
const customModes=new Set(["mom","geek","study","work"]);
function choose(list,avoid){
  const candidates=list.filter(item=>item!==avoid);
  const pool=candidates.length?candidates:list;
  return pool[Math.floor(Math.random()*pool.length)];
}
function basePhrase(mode){
  const config=modes[mode];
  const activity=$("activity").value.trim().slice(0,60);
  if(activity && config.templates && customModes.has(mode)){
    const template=choose(config.templates,null);
    return template.replaceAll("{activity}",activity);
  }
  return choose(config.lines,lastByMode[mode]);
}
function makePhrase(){
  const tone=$("tone").value;
  let phrase=basePhrase(current);
  if(tone!=="normal"){
    const lead=choose(tones[tone],null);
    phrase=lead+" "+phrase.charAt(0).toLowerCase()+phrase.slice(1);
  }
  if(tone==="drama") phrase+=" Это был тяжёлый, но необходимый этап моего личностного развития.";
  if(tone==="science") phrase+=" Погрешность исследования пока не позволяет сделать окончательный вывод.";
  if(tone==="official") phrase+=" Прошу считать изложенное шуточной формулировкой, не создающей правовых последствий.";
  lastByMode[current]=phrase;
  return phrase;
}
